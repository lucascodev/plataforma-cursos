import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { courseContentSchema } from '../contracts/course/course-content.schema.ts';

// supabase/seed.sql only feeds the local database (db reset and CI). Production content still goes through content:import.
const COURSES_DIR = new URL('../supabase/seed/courses/', import.meta.url);
const OUTPUT = new URL('../supabase/seed.sql', import.meta.url);
const QUOTE_TAG = '$course$';

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function readCourse(fileName: string): { slug: string; json: string } {
  const parsed = courseContentSchema.safeParse(JSON.parse(readFileSync(new URL(fileName, COURSES_DIR), 'utf8')));
  if (!parsed.success) fail(`Curso inválido em supabase/seed/courses/${fileName}. Rode pnpm content:import para ver os detalhes.`);
  const { $schema: _schema, ...content } = parsed.data;
  const json = JSON.stringify(content);
  if (json.includes(QUOTE_TAG)) fail(`O curso ${fileName} contém ${QUOTE_TAG}, que fecharia a string do SQL.`);
  return { slug: content.slug, json };
}

const statements = readdirSync(COURSES_DIR)
  .filter((fileName) => fileName.endsWith('.json'))
  .sort()
  .map(readCourse)
  .map(
    ({ slug, json }) =>
      `insert into public.courses (slug, content, published, listed)\nvalues ('${slug}', ${QUOTE_TAG}${json}${QUOTE_TAG}::jsonb, true, true)\non conflict (slug) do nothing;`,
  );

writeFileSync(OUTPUT, `-- Generated by pnpm db:seed from supabase/seed/courses. Do not edit by hand.\n\n${statements.join('\n\n')}\n`);
process.stdout.write('supabase/seed.sql updated.\n');
