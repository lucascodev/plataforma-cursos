import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { courseContentSchema } from '../contracts/course/course-content.schema.ts';

// supabase/seed.sql only feeds the local database (db reset and CI). Production courses are written in the editor.
const COURSES_DIR = new URL('../supabase/seed/courses/', import.meta.url);
const OUTPUT = new URL('../supabase/seed.sql', import.meta.url);
const QUOTE_TAG = '$course$';

function fail(message: string): never {
  console.error(message);
  process.exit(1);
}

function readCourse(fileName: string): { slug: string; json: string } {
  const parsed = courseContentSchema.safeParse(JSON.parse(readFileSync(new URL(fileName, COURSES_DIR), 'utf8')));
  if (!parsed.success) {
    const problems = parsed.error.issues.map((issue) => `  - ${issue.path.join('.') || '(raiz)'}: ${issue.message}`);
    fail(`Curso inválido em supabase/seed/courses/${fileName}:\n${problems.join('\n')}`);
  }
  const content = parsed.data;
  const json = JSON.stringify(content);
  if (json.includes(QUOTE_TAG)) fail(`O curso ${fileName} contém ${QUOTE_TAG}, que fecharia a string do SQL.`);
  return { slug: content.slug, json };
}

// The seed runs after the migrations, so it also creates the published version that the course_versions backfill
// gives every course in production.
const toStatements = ({ slug, json }: { slug: string; json: string }) =>
  [
    `insert into public.courses (slug, content, published, listed)\nvalues ('${slug}', ${QUOTE_TAG}${json}${QUOTE_TAG}::jsonb, true, true)\non conflict (slug) do nothing;`,
    `insert into public.course_versions (course_slug, status, semver, kind, content, published_at)\nselect c.slug, 'published', c.content ->> 'version', 'first', private.course_content_with_item_ids(c.content), now()\nfrom public.courses c\nwhere c.slug = '${slug}' and not exists (select 1 from public.course_versions v where v.course_slug = c.slug);`,
    `update public.courses c\nset content = v.content, published_version_id = v.id\nfrom public.course_versions v\nwhere c.slug = '${slug}' and v.course_slug = c.slug and v.status = 'published';`,
  ].join('\n\n');

const statements = readdirSync(COURSES_DIR)
  .filter((fileName) => fileName.endsWith('.json'))
  .sort()
  .map(readCourse)
  .map(toStatements);

writeFileSync(OUTPUT, `-- Generated by pnpm db:seed from supabase/seed/courses. Do not edit by hand.\n\n${statements.join('\n\n')}\n`);
process.stdout.write('supabase/seed.sql updated.\n');
